/* ─────────────────────────────────────────────────────────────
   StormCloud — generated by Bolt Bench
   7 runs · 300/300 pixels allocated
   3 root channels, 3 forks

   The colour math here is the same uint8 arithmetic the bench
   previews, and random16() is FastLED's own LCG, so seeding the
   same value reproduces the storm you tuned.

   300 px of state needs headroom: ESP32 / Teensy / RP2040.
   ───────────────────────────────────────────────────────────── */
