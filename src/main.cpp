/* ── tuning ─────────────────────────────────────────────────── */
#define GAP_MIN       1400
#define GAP_MAX       5200
#define DBL_CHANCE    70
#define CLUSTER_MS    180
#define LEAD_MIN      120
#define LEAD_MAX      240
#define TRAIL         34
#define TAPER         70
#define STRK_MIN      1
#define STRK_MAX      1
#define DUR_MIN       60
#define DUR_MAX       150
#define RGAP_MIN      30
#define RGAP_MAX      140
#define PARTIAL       0
#define FORK_DIM      120
#define FORK_FOLLOW   40
#define GLOW_MS       700
#define AMB_LEVEL     52
#define AMB_SPEED     14
#define CLOUD_FLASH   255
#define CLOUD_SPREAD  230
#define CLOUD_MS      1300
#define RUMBLE        150
#define MASTER        170
#define TINT          19

